"""Index original reference data without copying dialogue or game artwork.

Run from any directory. Reads sibling extracted assets and Korean pseudocode;
writes a reproducible source audit and native-symbol appendix under docs/.
Registry membership is evidence of a named capability, not recovered semantics.
"""
from __future__ import annotations

from collections import Counter
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PROJECTS = ROOT.parent
ASSETS = PROJECTS / "kss/assetpack1_dec/assets/assets"
NATIVE = PROJECTS / "korstu4CLAUDE/private-build/korean-base/analysis/decompiled/app/app.dart"


def read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def fingerprint(path: Path):
    return {
        "path_from_projects": path.relative_to(PROJECTS).as_posix(),
        "bytes": path.stat().st_size,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }


def walk(value):
    if isinstance(value, dict):
        yield value
        for child in value.values():
            yield from walk(child)
    elif isinstance(value, list):
        for child in value:
            yield from walk(child)


def main():
    global_root = ASSETS / "global_data"
    catalogs = {}
    for path in sorted(global_root.rglob("*.json")):
        if path.stem.endswith("_tw"):
            continue
        data = read_json(path)
        catalogs[path.relative_to(global_root).as_posix()] = {
            **fingerprint(path),
            "top_level_counts": {
                key: len(value) for key, value in data.items()
                if isinstance(value, (list, dict))
            } if isinstance(data, dict) else {"records": len(data)},
        }

    campaigns = []
    for story in read_json(global_root / "stories.json")["stories"]:
        directory = ASSETS / "stories" / str(story["id"])
        paths = sorted(p for p in directory.rglob("*.json") if not p.stem.endswith("_tw"))
        # The extracted island graph is only present under its _tw filename.
        if not (directory / "event/events.json").exists():
            alternate = directory / "event/events_tw.json"
            if alternate.exists():
                paths.append(alternate)
        functions = Counter()
        effects = Counter()
        predicates = Counter()
        list_counts = {}
        for path in paths:
            data = read_json(path)
            if isinstance(data, dict):
                for key, value in data.items():
                    if isinstance(value, list):
                        list_counts[f"{path.relative_to(directory).as_posix()}:{key}"] = len(value)
            for node in walk(data):
                code = node.get("funcCode")
                if isinstance(code, str) and code:
                    functions[code] += 1
                target = node.get("target")
                if isinstance(target, str) and target.startswith("FUNC_"):
                    predicates[target] += 1
                effect = node.get("type")
                if isinstance(effect, str) and "stat" in effect.lower():
                    effects[effect] += 1
        campaigns.append({
            "id": story["id"], "name": story["name"],
            "gameMode": story.get("gameMode"),
            "start": story["startDate"]["dateCode"],
            "end": story["endDate"]["dateCode"],
            "list_counts": list_counts,
            "funcCode_occurrences": dict(sorted(functions.items())),
            "predicate_occurrences": dict(sorted(predicates.items())),
            "stat_type_occurrences": dict(sorted(effects.items())),
            "sources": [fingerprint(path) for path in paths],
        })

    text = NATIVE.read_text(encoding="utf-8")
    registries = {}
    appendix = [
        "# Original-game native registry index", "",
        "Generated by `python tools/audit_original_game.py` from Korean sibling-build",
        "pseudocode. **Names and registration are observed; unresolved closure bodies",
        "do not establish exact behavior, arguments, odds or English availability.**",
        "Use [the functional reference](ORIGINAL-GAME-FUNCTIONS.md) for interpretation.", "",
    ]
    for name, label in [("init_usl", "Condition predicates"),
                        ("init_jvl", "Action/event effect verbs"),
                        ("init_EDl", "Timed effect verbs")]:
        match = re.search(r"^dynamic " + name + r"\(\) \{", text, re.M)
        if not match:
            raise ValueError(f"Registry not found: {name}")
        end = text.index("\n}", match.end())
        body = text[match.start():end]
        symbols = list(dict.fromkeys(re.findall(r'"([A-Z][A-Z_0-9]*)"', body)))
        if not symbols:
            raise ValueError(f"Empty registry: {name}")
        line = text.count("\n", 0, match.start()) + 1
        registries[name] = {"line": line, "count": len(symbols), "symbols": symbols}
        appendix += [f"## {label}: {len(symbols)} registered names", "",
                     f"Source: `app.dart:{line}`, `{name}`. Registration order retained.", "",
                     "| # | Symbol | Extracted campaigns using it (68 uses _tw graph) |",
                     "|---|---|---|"]
        for index, symbol in enumerate(symbols, 1):
            used = [str(story["id"]) for story in campaigns
                    if symbol in story["funcCode_occurrences"] or symbol in story["predicate_occurrences"]]
            appendix.append(f"| {index} | `{symbol}` | {', '.join(used) or 'Not found by this scan'} |")
        appendix += ["", "Usage scans include nested JSON funcCode/target fields, not runtime traces.",
                     "An absent match is not proof of an unused function; compiled call sites are outside this scan.", ""]

    output = {"scope": "Original extracted English catalogs and Korean sibling pseudocode; not d30mode output",
              "catalogs": catalogs, "campaigns": campaigns,
              "native": {**fingerprint(NATIVE), "registries": registries}}
    (ROOT / "docs/original-game-source-audit.json").write_text(
        json.dumps(output, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (ROOT / "docs/ORIGINAL-GAME-NATIVE-INDEX.md").write_text("\n".join(appendix), encoding="utf-8")
    print(f"Audited {len(catalogs)} global JSON catalogs, {len(campaigns)} campaigns;")
    print("native registry sizes:", {name: value["count"] for name, value in registries.items()})
    for story in campaigns:
        print(story["id"], {key: count for key, count in story["list_counts"].items()
                            if key in ["event/events.json:events", "data/locations.json:locations", "event/events_tw.json:events"]})


if __name__ == "__main__":
    main()
